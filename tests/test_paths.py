"""Live workspace resolution and explicit portable snapshot selection."""

from pathlib import Path

import pytest
from rebrew.workspace import WorkspaceConfigError, WorkspaceNotFound

from recoverage import config
from recoverage._paths import coverage_source


class TestCoverageSource:
    def test_finds_containing_project(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        (tmp_path / "rebrew-project.toml").write_text('[project]\nname = "live"\n')
        nested = tmp_path / "src" / "subsystem"
        nested.mkdir(parents=True)
        monkeypatch.chdir(nested)
        assert coverage_source() == tmp_path.resolve()

    def test_missing_project_requires_explicit_snapshots(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.chdir(tmp_path)
        with pytest.raises(WorkspaceNotFound):
            coverage_source()
        exported = tmp_path / "offline"
        exported.mkdir()
        monkeypatch.setenv("RECOVERAGE_SNAPSHOTS", str(exported))
        assert coverage_source() == exported

    def test_override_does_not_parse_an_unrelated_project(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        (tmp_path / "rebrew-project.toml").write_text("[broken")
        monkeypatch.chdir(tmp_path)
        exported = tmp_path / "offline"
        exported.mkdir()
        monkeypatch.setenv("RECOVERAGE_SNAPSHOTS", str(exported))
        assert coverage_source() == exported
        monkeypatch.delenv("RECOVERAGE_SNAPSHOTS")
        with pytest.raises(WorkspaceConfigError):
            coverage_source()

    def test_obsolete_database_override_is_rejected(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.setenv("RECOVERAGE_DB", "db")
        with pytest.raises(config.ConfigError, match="unknown configuration"):
            config.check_unknown_vars()


def _live_project(root: Path, *, bad: bool = False) -> None:
    import zlib

    (root / "rebrew-project.toml").write_text(
        '[project]\nname="live"\ndefault_target="good"\nshared_dir=""\n'
        '[compiler]\nprofile="msvc-6.0"\nincludes=""\nlibs=""\n'
        '[targets.good]\nbinary="game.exe"\nreversed_dir="src"\nmarker="GOOD"\n'
        'format="pe"\n' + ('[targets.bad]\nbinary="bad.exe"\narch="invalid-arch"\n' if bad else "")
    )
    (root / "src").mkdir()
    # Minimal one-section PE32 (RET at 0x401000), generated by Rebrew tests/bin_util.make_pe.
    (root / "game.exe").write_bytes(
        zlib.decompress(
            bytes.fromhex(
                "789cf38d62201b3430500e025c19187c181951c41e30303172337230a0880a4031183840d84c0c0c6c501118cda00011070166984601641ac99801047a25a915250c0c103f42fd0273370c28303024d0da1d87696dc1286018cc0000ccff0741"
            )
        )
    )


class TestLiveViewContracts:
    def test_live_configured_file_roots_need_no_exports(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        from conftest import wsgi_get

        _live_project(tmp_path)
        (tmp_path / "binaries").mkdir()
        (tmp_path / "reversed").mkdir()
        (tmp_path / "game.exe").rename(tmp_path / "binaries/game.exe")
        (tmp_path / "src").rename(tmp_path / "reversed/game")
        source = tmp_path / "reversed/game/main.c"
        source.write_bytes(b"int helper(void) { return 7; }\n")
        config = tmp_path / "rebrew-project.toml"
        config.write_text(
            config.read_text()
            .replace('binary="game.exe"', 'binary="binaries/game.exe"')
            .replace('reversed_dir="src"', 'reversed_dir="reversed/game"')
        )
        monkeypatch.chdir(tmp_path)
        status, _, body = wsgi_get("/files/good/source/main.c")
        assert status.startswith("200") and body == source.read_bytes()
        status, _, body = wsgi_get("/files/good/binary")
        assert status.startswith("200") and body == (tmp_path / "binaries/game.exe").read_bytes()
        assert not list(tmp_path.rglob("coverage-*.toml"))

    def test_failed_target_cannot_pass_cli_gate_or_return_empty_stats(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        import json

        from conftest import wsgi_request
        from typer.testing import CliRunner

        from recoverage.cli import app

        _live_project(tmp_path, bad=True)
        monkeypatch.chdir(tmp_path)
        runner = CliRunner()
        for args in (
            ["check", "--min-coverage", "0"],
            ["stats"],
            ["export"],
            ["check", "--target", "bad", "--min-coverage", "0"],
        ):
            result = runner.invoke(app, [*args, "--json"])
            assert result.exit_code == 2, result.output
            assert "invalid-arch" in json.loads(result.stdout)["error"], (args, result.output)
        assert runner.invoke(app, ["stats", "--target", "good", "--json"]).exit_code == 0
        status, _, body = wsgi_request("GET", "/api/targets/bad/stats")
        assert status.startswith("503"), body
        assert wsgi_request("GET", "/api/targets/good/stats")[0].startswith("200")

    def test_live_view_of_old_inputs_is_current(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        import json
        import os
        import time

        from conftest import wsgi_request

        from recoverage.regen import run_regen

        _live_project(tmp_path)
        old = time.time() - 10 * 24 * 3600
        for path in tmp_path.rglob("*"):
            os.utime(path, (old, old))
        monkeypatch.chdir(tmp_path)
        run_regen(tmp_path)
        status, _, body = wsgi_request("GET", "/api/health")
        assert status.startswith("200")
        assert json.loads(body)["status"] == "healthy"

    def test_offline_target_list_ignores_incidental_project(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        from coverage_fixture import write_coverage

        from recoverage.server import resolve_targets

        _live_project(tmp_path)
        portable = tmp_path / "portable"
        portable.mkdir()
        write_coverage(portable, "offline", {})
        monkeypatch.chdir(tmp_path)
        monkeypatch.setenv("RECOVERAGE_SNAPSHOTS", str(portable))
        assert resolve_targets() == [{"id": "offline", "name": "offline"}]
